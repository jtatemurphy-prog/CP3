def usd_path(pid: str) -> str:
    return os.path.join(USD_DIR, f"{pid}.usda")


def write_usds() -> list[str]:
    """Generate one USD per extra part: /Part (rigid body, mass, centre of mass), /Part/Visual box, /Part/Collision
    box (convex hull), metres, Z up, like the converted LEGO parts."""
    from pxr import Gf, Sdf, Usd, UsdGeom, UsdPhysics, UsdShade  # noqa: PLC0415

    os.makedirs(USD_DIR, exist_ok=True)
    out = []
    for pid, g in EXTRA_PARTS.items():
        path = usd_path(pid)
        stage = Usd.Stage.CreateNew(path)
        UsdGeom.SetStageUpAxis(stage, UsdGeom.Tokens.z)
        UsdGeom.SetStageMetersPerUnit(stage, 1.0)
        UsdPhysics.SetStageKilogramsPerUnit(stage, 1.0)
        root = UsdGeom.Xform.Define(stage, "/Part")
        stage.SetDefaultPrim(root.GetPrim())
        UsdPhysics.RigidBodyAPI.Apply(root.GetPrim())
        mass = UsdPhysics.MassAPI.Apply(root.GetPrim())
        lo, hi = [v * 1e-3 for v in g["lo"]], [v * 1e-3 for v in g["hi"]]
        c = [(a + b) / 2 for a, b in zip(lo, hi, strict=True)]
        mass.CreateMassAttr(g["mass_g"] * 1e-3)
        mass.CreateCenterOfMassAttr(Gf.Vec3f(*c))
        pts = [Gf.Vec3f(x, y, z) for x in (lo[0], hi[0]) for y in (lo[1], hi[1]) for z in (lo[2], hi[2])]
        faces = [0, 1, 3, 2, 4, 6, 7, 5, 0, 4, 5, 1, 2, 3, 7, 6, 0, 2, 6, 4, 1, 5, 7, 3]
        mat = UsdShade.Material.Define(stage, "/Part/Looks/Body")
        sh = UsdShade.Shader.Define(stage, "/Part/Looks/Body/Shader")
        sh.CreateIdAttr("UsdPreviewSurface")
        sh.CreateInput("diffuseColor", Sdf.ValueTypeNames.Color3f).Set(Gf.Vec3f(*g.get("color", (0.5, 0.5, 0.5))))
        sh.CreateInput("roughness", Sdf.ValueTypeNames.Float).Set(0.5)
        mat.CreateSurfaceOutput().ConnectToSource(sh.ConnectableAPI(), "surface")
        for scope, collide in (("Visual", False), ("Collision", True)):
            UsdGeom.Xform.Define(stage, f"/Part/{scope}")
            m = UsdGeom.Mesh.Define(stage, f"/Part/{scope}/box")
            m.CreatePointsAttr(pts)
            m.CreateFaceVertexCountsAttr([4] * 6)
            m.CreateFaceVertexIndicesAttr(faces)
            m.CreateExtentAttr([Gf.Vec3f(*lo), Gf.Vec3f(*hi)])
            if collide:
                UsdPhysics.CollisionAPI.Apply(m.GetPrim())
                UsdPhysics.MeshCollisionAPI.Apply(m.GetPrim()).CreateApproximationAttr("convexHull")
                UsdGeom.Imageable(m).CreatePurposeAttr("guide")
            else:
                UsdShade.MaterialBindingAPI.Apply(m.GetPrim()).Bind(mat)
        stage.GetRootLayer().Save()
        out.append(path)
    return out


